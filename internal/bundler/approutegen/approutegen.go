func validateViewQualifiedType(templatePath string, label string, viewType string) error {
	if strings.TrimSpace(viewType) == "" {
		return fmt.Errorf("%q has empty %s type", filepath.ToSlash(templatePath), label)
	}
	if !strings.Contains(viewType, ".") {
		return fmt.Errorf("%q %s type %q must be package qualified", filepath.ToSlash(templatePath), label, viewType)
	}
	if !strings.HasPrefix(viewType, viewPackageName+".") {
		return fmt.Errorf(
			"%q %s type %q must be %s-qualified",
			filepath.ToSlash(templatePath),
			label,
			viewType,
			viewPackageName,
		)
	}
	return nil
}

func validateNoDocumentTags(templatePath string) error {
	source, err := os.ReadFile(templatePath)
	if err != nil {
		return fmt.Errorf("read %q: %w", filepath.ToSlash(templatePath), err)
	}
	content := string(source)
	checks := []struct {
		label   string
		pattern *regexp.Regexp
	}{
		{label: "<html>", pattern: htmlTagPattern},
		{label: "<head>", pattern: headTagPattern},
		{label: "<body>", pattern: bodyTagPattern},
	}
	for _, check := range checks {
		if check.pattern.MatchString(content) {
			return fmt.Errorf(
				"%q contains %q; only root.templ may define document-level tags",
				filepath.ToSlash(templatePath),
				check.label,
			)
		}
	}
	return nil
}

func routeNameFromSegments(segments []routeSegment) string {
	if len(segments) == 0 {
		return "Root"
	}

	builder := strings.Builder{}
	for _, segment := range segments {
		switch segment.Kind {
		case frameworkrouter.SegmentDynamic:
			builder.WriteString("Param")
		case frameworkrouter.SegmentCatchAll:
			builder.WriteString("CatchAll")
		case frameworkrouter.SegmentOptionalCatchAll:
			builder.WriteString("OptionalCatchAll")
		case frameworkrouter.SegmentGroup:
			builder.WriteString("Group")
		case frameworkrouter.SegmentSlot:
			builder.WriteString("Slot")
		}
		builder.WriteString(pascalToken(segment.Name))
	}

	name := builder.String()
	if name == "" {
		return "Root"
	}
	return name
}

func routeParamsFromSegments(routeID string, segments []routeSegment) ([]routeParamDef, error) {
	params := make([]routeParamDef, 0, len(segments))
	seen := make(map[string]struct{})

	for _, segment := range segments {
		if !segment.IsParam() {
			continue
		}

		fieldName := pascalToken(segment.Name)
		if fieldName == "" {
			return nil, fmt.Errorf("route %q has invalid param name %q", routeID, segment.Name)
		}
		if _, ok := seen[fieldName]; ok {
			return nil, fmt.Errorf("route %q has duplicate param field %q", routeID, fieldName)
		}
		seen[fieldName] = struct{}{}

		params = append(params, routeParamDef{
			Name:      segment.Name,
			FieldName: fieldName,
			Type:      paramTypeForSegment(segment),
		})
	}

	return params, nil
}

func paramTypeForSegment(segment routeSegment) string {
	switch segment.Kind {
	case frameworkrouter.SegmentCatchAll, frameworkrouter.SegmentOptionalCatchAll:
		return "[]string"
	default:
		return "string"
	}
}

func writeTemplCopy(tpl templateDef) error {
	source, err := os.ReadFile(tpl.SourcePath)
	if err != nil {
		return fmt.Errorf("read %q: %w", tpl.SourcePath, err)
	}

	rewritten, err := rewritePackageDeclaration(source, tpl.Package)
	if err != nil {
		return fmt.Errorf("rewrite package for %q: %w", tpl.SourcePath, err)
	}

	if err := os.MkdirAll(tpl.OutputDir, 0o755); err != nil {
		return fmt.Errorf("create output dir %q: %w", tpl.OutputDir, err)
	}

	target := filepath.Join(tpl.OutputDir, tpl.OutputFile)
	if err := os.WriteFile(target, rewritten, 0o644); err != nil {
		return fmt.Errorf("write generated template %q: %w", target, err)
	}

	return nil
}

func rewritePackageDeclaration(source []byte, packageName string) ([]byte, error) {
	lines := strings.Split(string(source), "\n")
	for i, line := range lines {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, "package ") {
			continue
		}

		lines[i] = "package " + packageName

		firstNonEmpty := i + 1
		for firstNonEmpty < len(lines) && strings.TrimSpace(lines[firstNonEmpty]) == "" {
			firstNonEmpty++
		}
		if firstNonEmpty < len(lines) && strings.TrimSpace(lines[firstNonEmpty]) == generatedTemplHeader {
			return []byte(strings.Join(lines, "\n")), nil
		}

		rewritten := make([]string, 0, len(lines)+1)
		rewritten = append(rewritten, lines[:i+1]...)
		rewritten = append(rewritten, generatedTemplHeader)
		rewritten = append(rewritten, lines[i+1:]...)
		return []byte(strings.Join(rewritten, "\n")), nil
	}

	return nil, errors.New("template missing package declaration")
}

func rewriteGoPackageDeclaration(source []byte, packageName string) ([]byte, error) {
	lines := strings.Split(string(source), "\n")
	for idx, line := range lines {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, "package ") {
			continue
		}
		lines[idx] = "package " + packageName
		rewritten := strings.Join(lines, "\n")
		if strings.Contains(rewritten, generatedGoHeader) {
			return []byte(rewritten), nil
		}
		return []byte(generatedGoHeader + "\n" + rewritten), nil
	}
	return nil, errors.New("go source missing package declaration")
}

func writeSourcePackageCopy(sourcePackage sourcePackageDef, generatedRoot string) error {
	outputDir := filepath.Join(generatedRoot, sourcePackage.ModuleName)
	if err := os.MkdirAll(outputDir, 0o755); err != nil {
		return fmt.Errorf("create source package output %q: %w", outputDir, err)
	}

	for _, filePath := range sourcePackage.Files {
		source, err := os.ReadFile(filePath)
		if err != nil {
			return fmt.Errorf("read %q: %w", filePath, err)
		}
		rewritten, err := rewriteGoPackageDeclaration(source, sourcePackage.Package)
		if err != nil {
			return fmt.Errorf("rewrite package for %q: %w", filePath, err)
		}
		outPath := filepath.Join(outputDir, filepath.Base(filePath))
		if err := os.WriteFile(outPath, rewritten, 0o644); err != nil {
			return fmt.Errorf("write %q: %w", outPath, err)
		}
	}

	paramsSource, err := generateSourcePackageParamsFile(sourcePackage)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(outputDir, "params_gen.go"), paramsSource, 0o644); err != nil {
		return fmt.Errorf("write source params file for %q: %w", sourcePackage.InternalRouteID, err)
	}

	return nil
}

func generateSourcePackageParamsFile(sourcePackage sourcePackageDef) ([]byte, error) {
	buffer := &bytes.Buffer{}
	buffer.WriteString(generatedGoHeader + "\n")
	writef(buffer, "package %s\n\n", sourcePackage.Package)
	imports := []string{fmt.Sprintf("%q", frameworkModulePath+"/framework/router")}
	if len(sourcePackage.Params) > 0 {
		imports = append(imports, "\"strings\"")
	}
	for _, param := range sourcePackage.Params {
		if param.Type == "[]string" {
			imports = append(imports, "\"slices\"")
			break
		}
	}
	buffer.WriteString("import (\n")
	for _, line := range dedupeSorted(imports) {
		buffer.WriteString("\t" + line + "\n")
	}
	buffer.WriteString(")\n\n")
	writef(buffer, "type %s struct {\n", sourcePackage.ParamsTypeName)
	if len(sourcePackage.Params) == 0 {
		buffer.WriteString("}\n")
	} else {
		for _, param := range sourcePackage.Params {
			writef(buffer, "\t%s %s\n", param.FieldName, param.Type)
		}
		buffer.WriteString("}\n")
	}
	buffer.WriteString("\n")

	writef(buffer, "func ParseParams(requestPath string) (%s, bool) {\n", sourcePackage.ParamsTypeName)
	if len(sourcePackage.Params) == 0 {
		writef(buffer, "\t_, ok := router.MatchPathPattern(%q, requestPath)\n", routePattern(sourcePackage.PublicRouteID))
	} else {
		writef(
			buffer,
			"\tparams, ok := router.MatchPathPattern(%q, requestPath)\n",
			routePattern(sourcePackage.PublicRouteID),
		)
	}
	buffer.WriteString("\tif !ok {\n")
	writef(buffer, "\t\treturn %s{}, false\n", sourcePackage.ParamsTypeName)
	buffer.WriteString("\t}\n")
	writef(buffer, "\tout := %s{}\n", sourcePackage.ParamsTypeName)
	for _, param := range sourcePackage.Params {
		switch param.Type {
		case "[]string":
			writef(buffer, "\tif %sValue, exists := params[%q]; exists {\n", param.FieldName, param.Name)
			writef(buffer, "\t\tout.%s = slices.Clone(%sValue)\n", param.FieldName, param.FieldName)
			buffer.WriteString("\t}\n")
		default:
			writef(buffer, "\t%sValue, exists := params[%q]\n", param.FieldName, param.Name)
			buffer.WriteString("\tif !exists || len(" + param.FieldName + "Value) == 0 {\n")
			writef(buffer, "\t\treturn %s{}, false\n", sourcePackage.ParamsTypeName)
			buffer.WriteString("\t}\n")
			writef(buffer, "\tout.%s = strings.TrimSpace(%sValue[0])\n", param.FieldName, param.FieldName)
		}
	}
	buffer.WriteString("\treturn out, true\n")
	buffer.WriteString("}\n")

	formatted, err := format.Source(buffer.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format source params for %q: %w", sourcePackage.InternalRouteID, err)
	}
	return formatted, nil
}

func writeContractParamsStruct(buffer *bytes.Buffer, contract routeContractDef) {
	writef(buffer, "type %s struct {\n", contract.ParamsTypeName)
	if len(contract.Params) == 0 {
		buffer.WriteString("}\n\n")
		return
	}
	for _, param := range contract.Params {
		writef(buffer, "\t%s %s\n", param.FieldName, param.Type)
	}
	buffer.WriteString("}\n\n")
}

func buildRouteContracts(
	metas []routeMeta,
	layouts map[string]templateDef,
	defaults map[string]templateDef,
	notFounds map[string]templateDef,
) ([]routeContractDef, error) {
	contractsByRoute := make(map[string]routeContractDef, len(metas)+len(layouts)+len(defaults)+len(notFounds)+1)

	for _, meta := range metas {
		contractsByRoute[meta.RouteID] = routeContractDef{
			RouteID:         meta.RouteID,
			InternalRouteID: meta.InternalRouteID,
			PublicRouteID:   meta.PublicRouteID,
			RouteName:       meta.RouteName,
			ParamsTypeName:  meta.ParamsTypeName,
			Params:          meta.Params,
		}
	}

	for routeID, layout := range layouts {
		if _, ok := contractsByRoute[routeID]; ok {
			continue
		}
		params, err := routeParamsFromSegments(layout.PublicRouteID, layout.PublicSegments)
		if err != nil {
			return nil, err
		}
		routeName := routeNameFromSegments(layout.Segments)
		contractsByRoute[routeID] = routeContractDef{
			RouteID:         routeID,
			InternalRouteID: layout.InternalRouteID,
			PublicRouteID:   layout.PublicRouteID,
			RouteName:       routeName,
			ParamsTypeName:  routeName + "Params",
			Params:          params,
		}
	}

	for routeID, fallback := range defaults {
		if _, ok := contractsByRoute[routeID]; ok {
			continue
		}
		params, err := routeParamsFromSegments(fallback.PublicRouteID, fallback.PublicSegments)
		if err != nil {
			return nil, err
		}
		routeName := routeNameFromSegments(fallback.Segments)
		contractsByRoute[routeID] = routeContractDef{
			RouteID:         routeID,
			InternalRouteID: fallback.InternalRouteID,
			PublicRouteID:   fallback.PublicRouteID,
			RouteName:       routeName,
			ParamsTypeName:  routeName + "Params",
			Params:          params,
		}
	}

	for routeID, notFound := range notFounds {
		if _, ok := contractsByRoute[routeID]; ok {
			continue
		}
		params, err := routeParamsFromSegments(notFound.PublicRouteID, notFound.PublicSegments)
		if err != nil {
			return nil, err
		}
		routeName := routeNameFromSegments(notFound.Segments)
		contractsByRoute[routeID] = routeContractDef{
			RouteID:         routeID,
			InternalRouteID: notFound.InternalRouteID,
			PublicRouteID:   notFound.PublicRouteID,
			RouteName:       routeName,
			ParamsTypeName:  routeName + "Params",
			Params:          params,
		}
	}

	if _, ok := contractsByRoute[""]; !ok {
		contractsByRoute[""] = routeContractDef{
			RouteID:         "",
			InternalRouteID: "",
			PublicRouteID:   "",
			RouteName:       "Root",
			ParamsTypeName:  "RootParams",
		}
	}

	routeIDs := make([]string, 0, len(contractsByRoute))
	for routeID := range contractsByRoute {
		routeIDs = append(routeIDs, routeID)
	}
	sort.Strings(routeIDs)

	contracts := make([]routeContractDef, 0, len(routeIDs))
	for _, routeID := range routeIDs {
		contracts = append(contracts, contractsByRoute[routeID])
	}
	return contracts, nil
}

func contractsByRouteID(contracts []routeContractDef) map[string]routeContractDef {
	byRoute := make(map[string]routeContractDef, len(contracts))
	for _, contract := range contracts {
		byRoute[contract.RouteID] = contract
	}
	return byRoute
}

func mergeTemplateMaps(maps ...map[string]templateDef) map[string]templateDef {
	total := 0
	for _, items := range maps {
		total += len(items)
	}
	out := make(map[string]templateDef, total)
	for _, items := range maps {
		for routeID, tpl := range items {
			out[routeID] = tpl
		}
	}
	return out
}

func sortedTemplateRouteIDs(templates map[string]templateDef) []string {
	routeIDs := make([]string, 0, len(templates))
	for routeID := range templates {
		routeIDs = append(routeIDs, routeID)
	}
	sort.Strings(routeIDs)
	return routeIDs
}

func slotLayoutsFromOwners(slotOwners map[string][]slotDef) map[string]templateDef {
	out := make(map[string]templateDef)
	for _, slots := range slotOwners {
		for _, slot := range slots {
			for routeID, layout := range slot.Layouts {
				out[routeID] = layout
			}
		}
	}
	return out
}

func defaultsFromSlotOwners(slotOwners map[string][]slotDef) map[string]templateDef {
	out := make(map[string]templateDef)
	for _, slots := range slotOwners {
		for _, slot := range slots {
			if slot.Default != nil {
				out[slot.Default.RouteID] = *slot.Default
			}
		}
	}
	return out
}

func generateResolverNamespaceSource(
	paths projectlayout.ProjectLayout,
	metas []routeMeta,
	slotMetas []routeMeta,
	layouts map[string]templateDef,
	slotLayouts map[string]templateDef,
	defaults map[string]templateDef,
	notFounds map[string]templateDef,
) ([]byte, error) {
	allMetas := append(slices.Clone(metas), slotMetas...)
	allLayouts := mergeTemplateMaps(layouts, slotLayouts)
	contracts, err := buildRouteContracts(allMetas, allLayouts, defaults, notFounds)
	if err != nil {
		return nil, fmt.Errorf("build route contracts: %w", err)
	}
	contractsByID := contractsByRouteID(contracts)

	layoutRouteIDs := make([]string, 0, len(layouts))
	for routeID := range layouts {
		if routeID == "" {
			continue
		}
		layoutRouteIDs = append(layoutRouteIDs, routeID)
	}
	sort.Strings(layoutRouteIDs)
	layoutModelRouteIDs := sortedTemplateRouteIDs(allLayouts)
	defaultRouteIDs := sortedTemplateRouteIDs(defaults)
	notFoundRouteIDs := sortedTemplateRouteIDs(notFounds)

	buffer := &bytes.Buffer{}
	buffer.WriteString(generatedGoHeader + "\n")
	buffer.WriteString("package resolvers\n\n")
	buffer.WriteString("import (\n")
	buffer.WriteString("\t\"" + frameworkModulePath + "/framework\"\n")
	buffer.WriteString("\t\"" + frameworkModulePath + "/framework/metagen\"\n")
	buffer.WriteString("\t\"" + viewImportPath(paths) + "\"\n")
	buffer.WriteString("\t\"context\"\n")
	buffer.WriteString("\t\"net/http\"\n")
	buffer.WriteString(")\n\n")

	for _, contract := range contracts {
		writeContractParamsStruct(buffer, contract)
	}

	buffer.WriteString("type RouteResolver interface {\n")
	buffer.WriteString(
		"\tMetaGenRootLayout(meta framework.MetaContext[*view.Context]) " +
			"(metagen.Metadata, error)\n",
	)
	for _, routeID := range layoutRouteIDs {
		layout := layouts[routeID]
		contract, ok := contractsByID[routeID]
		if !ok {
			return nil, fmt.Errorf("missing route contract for layout route %q", routeID)
		}
		writef(
			buffer,
			"\t%s(meta framework.MetaContext[*view.Context], params %s) "+
				"(metagen.Metadata, error)\n",
			metaGenLayoutMethod(layout),
			contract.ParamsTypeName,
		)
	}
	for _, routeID := range layoutModelRouteIDs {
		layout := allLayouts[routeID]
		contract, ok := contractsByID[routeID]
		if !ok {
			return nil, fmt.Errorf("missing route contract for layout route %q", routeID)
		}
		writef(
			buffer,
			"\t%s(ctx context.Context, appCtx *view.Context, r *http.Request, params %s) (%s, error)\n",
			resolveLayoutMethod(layout),
			contract.ParamsTypeName,
			layout.ModelType,
		)
	}
	for _, routeID := range defaultRouteIDs {
		fallback := defaults[routeID]
		contract, ok := contractsByID[routeID]
		if !ok {
			return nil, fmt.Errorf("missing route contract for default route %q", routeID)
		}
		writef(
			buffer,
			"\t%s(ctx context.Context, appCtx *view.Context, r *http.Request, params %s) (%s, error)\n",
			resolveDefaultMethod(fallback),
			contract.ParamsTypeName,
			fallback.ModelType,
		)
	}
	for _, routeID := range notFoundRouteIDs {
		notFound := notFounds[routeID]
		contract, ok := contractsByID[routeID]
		if !ok {
			return nil, fmt.Errorf("missing route contract for not-found route %q", routeID)
		}
		writef(
			buffer,
			"\t%s(ctx context.Context, appCtx *view.Context, r *http.Request, "+
				"notFound framework.NotFoundContext, params %s) (%s, error)\n",
			resolveNotFoundMethod(notFound),
			contract.ParamsTypeName,
			notFound.ModelType,
		)
	}
	for _, meta := range metas {
		writef(
			buffer,
			"\t%s(meta framework.MetaContext[*view.Context], params %s) "+
				"(metagen.Metadata, error)\n",
			metaGenPageMethod(meta),
			meta.ParamsTypeName,
		)
	}
	for _, meta := range metas {
		writef(
			buffer,
			"\t%s(ctx context.Context, appCtx *view.Context, r *http.Request, params %s) (%s, error)\n",
			resolvePageMethod(meta),
			meta.ParamsTypeName,
			meta.PageViewType,
		)
	}
	for _, meta := range slotMetas {
		writef(
			buffer,
			"\t%s(ctx context.Context, appCtx *view.Context, r *http.Request, params %s) (%s, error)\n",
			resolvePageMethod(meta),
			meta.ParamsTypeName,
			meta.PageViewType,
		)
	}
	buffer.WriteString("}\n\n")
	buffer.WriteString("type Resolver struct{}\n\n")
	buffer.WriteString("var _ RouteResolver = (*Resolver)(nil)\n")

	formatted, err := format.Source(buffer.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format resolver namespace source: %w", err)
	}
	return formatted, nil
}

func generateRegistrySource(
	paths projectlayout.ProjectLayout,
	viewHooks viewcontract.Inspection,
	metas []routeMeta,
	slotMetas []routeMeta,
	slotOwners map[string][]slotDef,
	methodRoutes []methodRouteDef,
	root templateDef,
	layouts map[string]templateDef,
	notFounds map[string]templateDef,
) ([]byte, error) {
	if root.SourcePath == "" && root.ModuleName == "" {
		return nil, errors.New("missing root template metadata")
	}
	if _, ok := notFounds[""]; !ok {
		return nil, errors.New("missing root 404 template metadata")
	}
	allMetas := append(slices.Clone(metas), slotMetas...)
	allLayouts := mergeTemplateMaps(layouts, slotLayoutsFromOwners(slotOwners))
	defaults := defaultsFromSlotOwners(slotOwners)
	contracts, err := buildRouteContracts(allMetas, allLayouts, defaults, notFounds)
	if err != nil {
		return nil, fmt.Errorf("build route contracts: %w", err)
	}
	contractsByID := contractsByRouteID(contracts)
	slotNames := slotNamesByRoute(slotOwners)

	importLines := []string{
		"\"context\"",
		"\"net/http\"",
		"\"strings\"",
		fmt.Sprintf("%q", frameworkModulePath+"/framework"),
		fmt.Sprintf("frameworki18n %q", frameworkModulePath+"/framework/i18n"),
		fmt.Sprintf("%q", frameworkModulePath+"/framework/metagen"),
		fmt.Sprintf("%q", frameworkModulePath+"/framework/router"),
		fmt.Sprintf("%q", viewImportPath(paths)),
		fmt.Sprintf("route_resolvers %q", resolversImportPath(paths)),
		"\"github.com/a-h/templ\"",
	}
	if len(slotOwners) > 0 {
		importLines = append(importLines, "\"sync\"")
	}
	if anyParamsUseSlice(contracts) {
		importLines = append(importLines, "\"slices\"")
	}

	moduleImports := make([]string, 0, len(metas)+len(layouts)+len(notFounds)+1)
	moduleImports = append(moduleImports, fmt.Sprintf(
		"%s %q",
		root.ModuleName,
		generatedModuleImportPath(paths, root.ModuleName),
	))
	for _, meta := range metas {
		moduleImports = append(moduleImports, fmt.Sprintf(
			"%s %q",
			meta.Page.ModuleName,
			generatedModuleImportPath(paths, meta.Page.ModuleName),
		))
	}
	for _, meta := range slotMetas {
		moduleImports = append(moduleImports, fmt.Sprintf(
			"%s %q",
			meta.Page.ModuleName,
			generatedModuleImportPath(paths, meta.Page.ModuleName),
		))
	}

	layoutKeys := make([]string, 0, len(layouts))
	for routeID := range layouts {
		layoutKeys = append(layoutKeys, routeID)
	}
	sort.Strings(layoutKeys)
	for _, routeID := range layoutKeys {
		layout := layouts[routeID]
		moduleImports = append(moduleImports, fmt.Sprintf(
			"%s %q",
			layout.ModuleName,
			generatedModuleImportPath(paths, layout.ModuleName),
		))
	}
	slotLayoutKeys := make([]string, 0, len(slotOwners))
	for owner := range slotOwners {
		slotLayoutKeys = append(slotLayoutKeys, owner)
	}
	sort.Strings(slotLayoutKeys)
	for _, owner := range slotLayoutKeys {
		for _, slot := range slotOwners[owner] {
			if slot.Default != nil {
				moduleImports = append(moduleImports, fmt.Sprintf(
					"%s %q",
					slot.Default.ModuleName,
					generatedModuleImportPath(paths, slot.Default.ModuleName),
				))
			}
			layoutKeys := make([]string, 0, len(slot.Layouts))
			for routeID := range slot.Layouts {
				layoutKeys = append(layoutKeys, routeID)
			}
			sort.Strings(layoutKeys)
			for _, routeID := range layoutKeys {
				layout := slot.Layouts[routeID]
				moduleImports = append(moduleImports, fmt.Sprintf(
					"%s %q",
					layout.ModuleName,
					generatedModuleImportPath(paths, layout.ModuleName),
				))
			}
		}
	}

	notFoundKeys := make([]string, 0, len(notFounds))
	for routeID := range notFounds {
		notFoundKeys = append(notFoundKeys, routeID)
	}
	sort.Strings(notFoundKeys)
	for _, routeID := range notFoundKeys {
		notFound := notFounds[routeID]
		moduleImports = append(moduleImports, fmt.Sprintf(
			"%s %q",
			notFound.ModuleName,
			generatedModuleImportPath(paths, notFound.ModuleName),
		))
	}
	for _, route := range methodRoutes {
		moduleImports = append(moduleImports, fmt.Sprintf(
			"%s %q",
			route.PackageAlias,
			generatedModuleImportPath(paths, route.PackageModule),
		))
	}

	moduleImports = dedupeSorted(moduleImports)
	importLines = append(importLines, moduleImports...)

	buffer := &bytes.Buffer{}
	buffer.WriteString(generatedGoHeader + "\n")
	buffer.WriteString("package gen\n\n")
	buffer.WriteString("import (\n")
	for _, line := range importLines {
		buffer.WriteString("\t" + line + "\n")
	}
	buffer.WriteString(")\n\n")

	buffer.WriteString("type RouteResolvers = route_resolvers.RouteResolver\n\n")
	for _, meta := range metas {
		writef(buffer, "type %s = route_resolvers.%s\n", meta.ParamsTypeName, meta.ParamsTypeName)
	}
	if len(metas) > 0 {
		buffer.WriteString("\n")
	}
	buffer.WriteString("func NewRouteResolvers() RouteResolvers {\n")
	buffer.WriteString("\treturn &route_resolvers.Resolver{}\n")
	buffer.WriteString("}\n\n")

	buffer.WriteString(
		"func NotFoundPage(resolvers RouteResolvers) " +
			"func(appCtx *view.Context, r *http.Request, notFound framework.NotFoundContext) (templ.Component, error) {\n",
	)
	buffer.WriteString(
		"	return func(appCtx *view.Context, r *http.Request, " +
			"notFound framework.NotFoundContext) (templ.Component, error) {\n",
	)
	buffer.WriteString("		return renderNotFoundPage(resolvers, appCtx, r, notFound)\n")
	buffer.WriteString("	}\n")
	buffer.WriteString("}\n\n")

	buffer.WriteString("func requestContext(r *http.Request) context.Context {\n")
	buffer.WriteString("	if r == nil {\n")
	buffer.WriteString("		return context.Background()\n")
	buffer.WriteString("	}\n")
	buffer.WriteString("	return r.Context()\n")
	buffer.WriteString("}\n\n")

	buffer.WriteString(
		"func withNotFoundRequestInfo(r *http.Request, " +
			"notFound framework.NotFoundContext) *http.Request {\n",
	)
	buffer.WriteString("	if r == nil {\n")
	buffer.WriteString("		return nil\n")
	buffer.WriteString("	}\n")
	buffer.WriteString("	info, _ := frameworki18n.RequestInfoFromContext(r.Context())\n")
	buffer.WriteString("	info.Locale = strings.TrimSpace(notFound.Locale)\n")
	buffer.WriteString("	if strings.TrimSpace(info.OriginalPath) == \"\" {\n")
	buffer.WriteString("		info.OriginalPath = strings.TrimSpace(notFound.RequestPath)\n")
	buffer.WriteString("	}\n")
	buffer.WriteString("	if strings.TrimSpace(info.StrippedPath) == \"\" {\n")
	buffer.WriteString("		info.StrippedPath = notFoundStrippedPath(notFound)\n")
	buffer.WriteString("	}\n")
	buffer.WriteString("	return r.WithContext(frameworki18n.WithRequestInfo(r.Context(), info))\n")
	buffer.WriteString("}\n\n")

	buffer.WriteString("func notFoundStrippedPath(notFound framework.NotFoundContext) string {\n")
	buffer.WriteString("	requestPath := strings.TrimSpace(notFound.RequestPath)\n")
	buffer.WriteString("	if requestPath == \"\" {\n")
	buffer.WriteString("		return \"/\"\n")
	buffer.WriteString("	}\n")
	buffer.WriteString("	locale := strings.TrimSpace(notFound.Locale)\n")
	buffer.WriteString("	if locale == \"\" {\n")
	buffer.WriteString("		return requestPath\n")
	buffer.WriteString("	}\n")
	buffer.WriteString("	prefix := \"/\" + locale\n")
	buffer.WriteString("	if requestPath == prefix {\n")
	buffer.WriteString("		return \"/\"\n")
	buffer.WriteString("	}\n")
	buffer.WriteString("	if strings.HasPrefix(requestPath, prefix+\"/\") {\n")
	buffer.WriteString("		return strings.TrimPrefix(requestPath, prefix)\n")
	buffer.WriteString("	}\n")
	buffer.WriteString("	return requestPath\n")
	buffer.WriteString("}\n\n")

	buffer.WriteString("func Handlers(resolvers RouteResolvers) []framework.RouteHandler[*view.Context] {\n")
	buffer.WriteString("\treturn []framework.RouteHandler[*view.Context]{\n")
	for _, meta := range metas {
		writef(
			buffer,
			"\t\tframework.PageOnlyRouteHandler[*view.Context, %s, %s]{\n",
			meta.ParamsTypeName,
			meta.PageViewType,
		)

		if err := writePageModule(
			buffer,
			meta,
			root,
			layouts,
			contractsByID,
		); err != nil {
			return nil, err
		}
		buffer.WriteString("\t\t},\n")
	}
	for _, route := range methodRoutes {
		writef(
			buffer,
			"\t\tframework.MethodOnlyRouteHandler[*view.Context, %s.%s]{\n",
			route.PackageAlias,
			route.ParamsTypeName,
		)
		writef(
			buffer,
			"\t\t\tRoute: framework.MethodRouteModule[*view.Context, %s.%s]{\n",
			route.PackageAlias,
			route.ParamsTypeName,
		)
		writef(buffer, "\t\t\t\tRouteID: %q,\n", route.InternalRouteID)
		writef(buffer, "\t\t\t\tPattern: %q,\n", routePattern(route.PublicRouteID))
		writef(buffer, "\t\t\t\tParseParams: %s.ParseParams,\n", route.PackageAlias)
		for _, method := range route.Methods {
			writef(buffer, "\t\t\t\t%s: %s.%s,\n", method, route.PackageAlias, method)
		}
		buffer.WriteString("\t\t\t},\n")
		buffer.WriteString("\t\t},\n")
	}
	buffer.WriteString("\t}\n")
	buffer.WriteString("}\n\n")

	if err := writeNotFoundPageFunc(buffer, root, layouts, notFounds, slotNames, contractsByID); err != nil {
		return nil, err
	}

	for _, contract := range contracts {
		writeParseParamsFunc(buffer, contract)
	}
	if err := writeSlotResolveFuncs(buffer, slotOwners, slotNames, contractsByID); err != nil {
		return nil, err
	}
	for _, meta := range metas {
		if err := writeComposeFunc(buffer, meta, slotOwners, slotNames, layouts, contractsByID); err != nil {
			return nil, err
		}
	}

	formatted, err := format.Source(buffer.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format registry source: %w", err)
	}
	return formatted, nil
}

func anyParamsUseSlice(contracts []routeContractDef) bool {
	for _, contract := range contracts {
		for _, param := range contract.Params {
			if param.Type == "[]string" {
				return true
			}
		}
	}
	return false
}

