func Run(cfg Config) error {
	paths := cfg.Layout
	if strings.TrimSpace(paths.RoutesDir) == "" {
		return errors.New("project layout routes dir is required")
	}
	if strings.TrimSpace(paths.GeneratedDir) == "" {
		return errors.New("project layout generated dir is required")
	}
	if strings.TrimSpace(paths.ResolversDir) == "" {
		return errors.New("project layout resolvers dir is required")
	}
	if strings.TrimSpace(paths.ViewDir) == "" {
		return errors.New("project layout view dir is required")
	}

	routes, err := discoverRouteFiles(paths.RoutesDir, paths.GeneratedDir)
	if err != nil {
		return err
	}
	if len(routes.Pages) == 0 && len(routes.MethodRoutes) == 0 {
		return errors.New("no page.templ or route.go files found in web/routes")
	}
	if routes.Root.SourcePath == "" {
		return errors.New("root template is required: web/routes/root.templ")
	}
	if _, ok := routes.NotFounds[""]; !ok {
		return errors.New("root 404 template is required: web/routes/404.templ")
	}
	if err := inspectRouteTemplateModels(&routes); err != nil {
		return err
	}
	if err := validateRootTemplateSignature(routes.Root.SourcePath); err != nil {
		return err
	}
	for _, tpl := range routes.Templates {
		if tpl.Kind == rootTemplate {
			continue
		}
		if err := validateNoDocumentTags(tpl.SourcePath); err != nil {
			return err
		}
	}
	if err := validateDiscoveryConventions(paths, &routes.Discovery); err != nil {
		return err
	}
	viewHooks, err := viewcontract.Inspect(paths.ViewDir)
	if err != nil {
		return fmt.Errorf("inspect view contract: %w", err)
	}

	metas, err := buildRouteMetas(routes.Pages, paths)
	if err != nil {
		return err
	}
	slotMetas, err := buildRouteMetas(routes.SlotPages, paths)
	if err != nil {
		return err
	}
	if err := validateMethodRoutes(paths, routes.MethodRoutes); err != nil {
		return err
	}
	slotOwners := buildSlotOwners(slotMetas, routes.SlotLayouts, routes.Defaults)

	if err := os.RemoveAll(paths.GeneratedDir); err != nil {
		return fmt.Errorf("clear generated output: %w", err)
	}
	if err := os.MkdirAll(paths.GeneratedDir, 0o755); err != nil {
		return fmt.Errorf("create generated output root: %w", err)
	}

	for _, tpl := range routes.Templates {
		if err := writeTemplCopy(tpl); err != nil {
			return err
		}
	}
	for _, sourcePkg := range routes.SourcePackages {
		if err := writeSourcePackageCopy(sourcePkg, paths.GeneratedDir); err != nil {
			return err
		}
	}

	resolversSource, err := generateResolverNamespaceSource(
		paths,
		metas,
		slotMetas,
		routes.Layouts,
		routes.SlotLayouts,
		routes.Defaults,
		routes.NotFounds,
	)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(paths.ResolversDir, 0o755); err != nil {
		return fmt.Errorf("create resolver namespace root %q: %w", paths.ResolversDir, err)
	}
	resolverFilePath := filepath.Join(paths.ResolversDir, generatedResolverFileName)
	if err := os.WriteFile(resolverFilePath, resolversSource, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", generatedResolverFileName, err)
	}

	registrySource, err := generateRegistrySource(
		paths,
		viewHooks,
		metas,
		slotMetas,
		slotOwners,
		routes.MethodRoutes,
		routes.Root,
		routes.Layouts,
		routes.NotFounds,
	)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(paths.GeneratedDir, "registry_gen.go"), registrySource, 0o644); err != nil {
		return fmt.Errorf("write registry_gen.go: %w", err)
	}
	discoverySource, err := generateDiscoverySource(paths, routes.Discovery)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(paths.GeneratedDir, "discovery_gen.go"), discoverySource, 0o644); err != nil {
		return fmt.Errorf("write discovery_gen.go: %w", err)
	}
	bundleSource, err := generateBundleSource(paths, viewHooks)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(paths.GeneratedDir, "bundle_gen.go"), bundleSource, 0o644); err != nil {
		return fmt.Errorf("write bundle_gen.go: %w", err)
	}

	return nil
}

func appImportPath(modulePath string, relativePath string) string {
	trimmedModulePath := strings.TrimSpace(modulePath)
	trimmedRelativePath := strings.Trim(strings.TrimSpace(relativePath), "/")
	if trimmedRelativePath == "" {
		return trimmedModulePath
	}
	return path.Join(trimmedModulePath, trimmedRelativePath)
}

